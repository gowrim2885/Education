 class Students {
    constructor() {
        this.id = "";
        this.name = "";
        this.department = "";
        this.year;
        this.age = 0;
        this.subject ;
        this.gender = "";
    }

    SetId(value) {
        this.id = value;
    }
    SetName(value) {
        this.name = value;
    }
    SetDepartment(value) {
        this.department = value;
    }
    SetYear(value) {
        this.year = value;
    }
    SetAge(value) {
        this.age = value
    }
    SetSubject(value) {
        this.subject = value;
    }
    SetGender(value) {
        this.gender = value;
    }

}


